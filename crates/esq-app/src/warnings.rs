//! SketchUp's message boxes: plain warnings (`QMessageBox::warning`, an OK button) and the
//! questions that offer to stop asking. A question the user stopped is skipped from then on,
//! as if answered with its usual answer, until Preferences › General › « Réinitialiser tous
//! les messages d'avertissement » shows them all again (SketchUp turns SketchUp's
//! `Show…` preferences back on). The keys are SketchUp's preference names.
//!
//! The questions SketchUp can stop, and what Esquisse does of them:
//!
//! | Preference | Situation | In Esquisse |
//! |---|---|---|
//! | `ShowStylesWarning` | a scene added or updated with style changes not saved (« Attention - Scènes et styles ») | yes (`scenes.rs`) |
//! | `ShowSectionToolDlg` | a section plane placed (« Donner un nom au plan de section ») | yes (`tools/section.rs`) |
//! | `ShowPhotorealQuestionDlg` | photoreal materials turned on (« Activer les matériaux photoréalistes ») | yes (`commands.rs`, Styles) |
//! | `NoPromptHideCurLayer` | the current tag unticked (« Vous ne pouvez pas masquer l'étiquette actuelle. ») | yes (`tags_panel.rs`) |
//! | `ShowClassifierWarning` | a type given to a selection holding what cannot be classified | no: Esquisse's Classifier gives a type to what is clicked |
//! | `ShowAttributeWarning` | advanced attributes given to a mixed selection | no: Entity Info edits them for one component |
//! | `ShowGeoReferenceWarning` | a manual location over a location snapshot and terrain | no: no snapshot (a Trimble service) |
//! | `ShowMergeHiddenLayerMsg`, `InvalidFilePathsDlg`, `GlInitInformationDlg`, `LastOSVersionWarn` | merging with hidden geometry, missing files of a model, graphics card, Windows version | no such message in Esquisse |
//! | `ShowAgentAimmInfoDlg` | textures generated by Trimble's AI | no: online service |

use std::cell::RefCell;

use eframe::egui;

use crate::app::EsquisseApp;

/// What the user chose: the button (0 = the first), the choice (questions with radio
/// buttons) and the fields as typed.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Answer {
    pub button: usize,
    pub choice: usize,
    pub fields: Vec<String>,
}

type OnAnswer = Box<dyn FnOnce(&mut EsquisseApp, Answer)>;

/// A message to show.
pub struct Message {
    /// The preference that stops it (`ShowStylesWarning`…); `None` for a plain warning.
    pub key: Option<&'static str>,
    pub title: String,
    pub text: String,
    /// Radio choices under the text (Scenes and Styles).
    pub choices: Vec<String>,
    pub choice: usize,
    /// Text fields: label and value (Name Section Plane).
    pub fields: Vec<(String, String)>,
    pub buttons: Vec<String>,
    /// The tick box that stops the message, with SketchUp's words.
    pub check: Option<String>,
    /// The button and choice taken without asking once the message is stopped.
    pub usual: (usize, usize),
    on_answer: Option<OnAnswer>,
}

impl Message {
    /// A plain warning with an OK button.
    pub fn warning(text: impl Into<String>) -> Message {
        Message {
            key: None,
            title: "Esquisse".into(),
            text: text.into(),
            choices: Vec::new(),
            choice: 0,
            fields: Vec::new(),
            buttons: vec!["OK".into()],
            check: None,
            usual: (0, 0),
            on_answer: None,
        }
    }

    /// A question the user may stop (`key`), with its tick box label.
    pub fn question(key: &'static str, title: &str, text: &str, buttons: &[&str], check: &str) -> Message {
        Message {
            key: Some(key),
            title: title.into(),
            buttons: buttons.iter().map(|b| b.to_string()).collect(),
            check: Some(check.into()),
            ..Message::warning(text)
        }
    }

    pub fn choices(mut self, choices: &[&str], first: usize) -> Message {
        self.choices = choices.iter().map(|c| c.to_string()).collect();
        self.choice = first;
        self
    }

    pub fn fields(mut self, fields: &[(&str, &str)]) -> Message {
        self.fields = fields.iter().map(|(l, v)| (l.to_string(), v.to_string())).collect();
        self
    }

    /// The answer taken once the message is stopped: `button`, `choice`.
    pub fn usual(mut self, button: usize, choice: usize) -> Message {
        self.usual = (button, choice);
        self
    }

    pub fn then(mut self, f: impl FnOnce(&mut EsquisseApp, Answer) + 'static) -> Message {
        self.on_answer = Some(Box::new(f));
        self
    }
}

#[derive(Default)]
struct State {
    queue: Vec<(Message, bool)>,
}

thread_local! {
    static STATE: RefCell<State> = RefCell::new(State::default());
}

/// Whether the user stopped message `key`.
pub fn stopped(key: &str) -> bool {
    crate::settings::with(|s| s.dismissed.contains(key))
}

/// Shows `m`, or, when the user stopped it, answers it at once with its usual answer.
pub fn show(app: &mut EsquisseApp, mut m: Message) {
    if m.key.is_some_and(stopped) {
        let a =
            Answer { button: m.usual.0, choice: m.usual.1, fields: m.fields.iter().map(|(_, v)| v.clone()).collect() };
        if let Some(f) = m.on_answer.take() {
            f(app, a);
        }
        return;
    }
    STATE.with(|s| s.borrow_mut().queue.push((m, false)));
}

/// [`show`] from where the application is out of reach (a tool): a stopped message is
/// dropped, its usual answer being to do nothing more.
pub fn queue(m: Message) {
    if m.key.is_some_and(stopped) {
        return;
    }
    STATE.with(|s| s.borrow_mut().queue.push((m, false)));
}

/// View › Face Style › Photoreal Materials turned on (preference
/// `ShowPhotorealQuestionDlg`): SketchUp first says what they need, and OK turns them on
/// with an environment (the model's first one, else the first that comes with the
/// application) when the model has none in use.
pub fn turn_photoreal_on(app: &mut EsquisseApp) {
    let m = Message::question(
        "ShowPhotorealQuestionDlg",
        "Activer les matériaux photoréalistes",
        "Les matériaux seront rendus en temps réel sur la base de textures photoréelles et d'un environnement.",
        &["OK", "Annuler"],
        "Ne plus montrer",
    )
    .then(|app, a| {
        if a.button != 0 {
            return;
        }
        app.style.photoreal = true;
        app.doc.rev += 1;
        if crate::environments::current(&app.doc.model).is_some() {
            return;
        }
        let first = crate::environments::list(&app.doc.model).first().map(|e| e.id);
        let shipped = || {
            let dir = crate::environments::shipped_dir()?;
            let item = crate::environments::read_folder(&dir).into_iter().next()?;
            crate::environments::from_file(&item.path).ok()
        };
        match first {
            Some(id) => app.doc.commit("Environnement", |m, _| crate::environments::set_current(m, Some(id))),
            None => {
                if let Some((e, blob)) = shipped() {
                    app.doc.commit("Environnement", |m, _| {
                        let id = crate::environments::add(m, e, Some(blob));
                        crate::environments::set_current(m, Some(id));
                    });
                }
            }
        }
    });
    show(app, m);
}

/// A plain warning.
pub fn warn(text: impl Into<String>) {
    STATE.with(|s| s.borrow_mut().queue.push((Message::warning(text), false)));
}

/// Tests: the text of the message in front, if any.
#[cfg(test)]
pub fn front() -> Option<String> {
    STATE.with(|s| s.borrow().queue.first().map(|(m, _)| m.text.clone()))
}

/// Tests: drops every message waiting.
#[cfg(test)]
pub fn clear() {
    STATE.with(|s| s.borrow_mut().queue.clear());
}

/// Every frame: the message in front, until answered.
pub fn window(app: &mut EsquisseApp, ctx: &egui::Context) {
    let Some((mut m, mut checked)) = STATE.with(|s| {
        let mut s = s.borrow_mut();
        if s.queue.is_empty() { None } else { Some(s.queue.remove(0)) }
    }) else {
        return;
    };
    let mut answer = None;
    crate::ui::centered(&m.title.clone()).id(egui::Id::unique("warning_box")).show(ctx, |ui| {
        ui.set_max_width(460.0);
        if !m.text.is_empty() {
            ui.label(m.text.as_str());
        }
        if !m.fields.is_empty() {
            egui::Grid::new("warning_fields").num_columns(2).show(ui, |ui| {
                for (label, value) in m.fields.iter_mut() {
                    let l = ui.label(label.as_str());
                    let r = ui.add(egui::TextEdit::singleline(value).desired_width(220.0)).labelled_by(l.id);
                    crate::dialogs::name_widget(ui, &r, label, Some(value.as_str()));
                    ui.end_row();
                }
            });
        }
        if !m.choices.is_empty() {
            ui.add_space(4.0);
            for (i, c) in m.choices.iter().enumerate() {
                ui.radio_value(&mut m.choice, i, c.as_str());
            }
        }
        if let Some(c) = &m.check {
            ui.add_space(4.0);
            ui.checkbox(&mut checked, c.as_str());
        }
        ui.add_space(6.0);
        ui.horizontal(|ui| {
            for (i, b) in m.buttons.iter().enumerate() {
                if ui.button(b.as_str()).clicked() {
                    answer = Some(i);
                }
            }
        });
    });
    match answer {
        Some(button) => {
            if checked && let Some(k) = m.key {
                crate::settings::update(|s| {
                    s.dismissed.insert(k.to_string());
                });
            }
            let a = Answer { button, choice: m.choice, fields: m.fields.iter().map(|(_, v)| v.clone()).collect() };
            if let Some(f) = m.on_answer.take() {
                f(app, a);
            }
        }
        None => STATE.with(|s| s.borrow_mut().queue.insert(0, (m, checked))),
    }
}
